_CODE_TO_NAME = {code.lower(): name for name, code in LANG_MAP.items()}


def resolve(lang_name) -> "str | None":
    """解析语言名：支持全称、简称、Hy-MT2 缩写。返回规范中文名，非法时返回 None。"""
    if not isinstance(lang_name, str):
        return None
    name = lang_name.strip()
    if name in LANG_MAP:
        return name
    if name in ALIASES:
        return ALIASES[name]
    return _CODE_TO_NAME.get(name.lower())


def is_supported(lang_name) -> bool:
    """语言是否在 Hy-MT2 支持范围内"""
    return resolve(lang_name) is not None


def list_languages():
    """列出所有支持的语言（调试用）。"""
    for name, code in LANG_MAP.items():
        print(f"  {name:8s} → {code}")
